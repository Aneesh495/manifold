#!/usr/bin/env python3
"""
tools/ectrans.py
Self-contained eC source preprocessor and translator.
Translates idiomatic eC syntax (classes, properties, bitclasses, imports)
into standard C11 for zero-dependency compilation across macOS and Linux.
"""

import sys
import os
import re
import argparse

def process_ec_file(filepath):
    """Reads and parses an eC source or header file into C11."""
    if not os.path.exists(filepath):
        return f"// File not found: {filepath}\n"

    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    # Replace import statements with include
    # e.g., import "types" -> #include "types.eh"
    content = re.sub(r'^\s*import\s+["<]([^">]+)[">]\s*;', r'#include "\1.eh"', content, flags=re.MULTILINE)

    return content

def bundle_directory(src_dirs, output_file, is_test=False):
    """Bundles all .ec and .eh files from directories into an amalgamated C11 translation unit."""
    files_to_process = []
    runner_file = None

    if is_test:
        for root, _, files in os.walk("tests"):
            for f in sorted(files):
                if f.endswith('.ec'):
                    full_path = os.path.join(root, f)
                    if f == "test_runner.ec":
                        runner_file = full_path
                    elif f == "bench_runner.ec":
                        continue
                    else:
                        files_to_process.append(full_path)
        files_to_process.sort()
        if runner_file:
            files_to_process.append(runner_file)
    else:
        for sdir in src_dirs:
            for root, _, files in os.walk(sdir):
                for f in sorted(files):
                    if f.endswith('.ec') or f.endswith('.eh'):
                        if f in ('main.ec', 'test_runner.ec', 'bench_runner.ec', 'DiagTerminal.ec'):
                            continue
                        files_to_process.append(os.path.join(root, f))

        def sort_key(path):
            if path.endswith('.eh'):
                return (0, path)
            if 'types' in path.lower() or 'core' in path.lower():
                return (1, path)
            if 'can' in path.lower() or 'isotp' in path.lower():
                return (2, path)
            if 'uds' in path.lower() or 'doip' in path.lower():
                return (3, path)
            if 'someip' in path.lower() or 'xcp' in path.lower():
                return (4, path)
            if 'secoc' in path.lower() or 'dbc' in path.lower():
                return (5, path)
            if 'routing' in path.lower() or 'dtc' in path.lower():
                return (6, path)
            return (7, path)

        files_to_process.sort(key=sort_key)

    os.makedirs(os.path.dirname(os.path.abspath(output_file)), exist_ok=True)
    with open(output_file, 'w', encoding='utf-8') as out:
        out.write("// Auto-generated by ectrans.py. Do not edit directly.\n")
        out.write("#include \"ec_runtime.h\"\n")
        out.write("#include \"manifold.eh\"\n\n")

        for fpath in files_to_process:
            rel = os.path.relpath(fpath)
            out.write(f"\n// ============================================================================\n")
            out.write(f"// BEGIN: {rel}\n")
            out.write(f"// ============================================================================\n\n")
            out.write(process_ec_file(fpath))
            out.write(f"\n// END: {rel}\n")

def main():
    parser = argparse.ArgumentParser(description="eC source translator and bundler")
    parser.add_argument("-i", "--input", help="Input eC source file")
    parser.add_argument("-o", "--output", required=True, help="Output C file")
    parser.add_argument("--bundle-src", action="store_true", help="Bundle all src/ eC files")
    parser.add_argument("--bundle-tests", action="store_true", help="Bundle all test eC files")

    args = parser.parse_args()

    if args.bundle_src:
        bundle_directory(["src"], args.output, is_test=False)
    elif args.bundle_tests:
        bundle_directory(["tests"], args.output, is_test=True)
    elif args.input:
        os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
        with open(args.output, 'w', encoding='utf-8') as out:
            out.write("// Auto-generated by ectrans.py. Do not edit directly.\n")
            out.write("#include \"ec_runtime.h\"\n")
            out.write("#include \"manifold.eh\"\n\n")
            out.write(process_ec_file(args.input))
    else:
        parser.print_help()
        sys.exit(1)

if __name__ == "__main__":
    main()
